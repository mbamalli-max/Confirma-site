// Writes admin/catalog-labels.js from the app catalog (names only; no aliases, no descriptions).
// Run: node tools/admin/build-catalog-labels.mjs   — tests check the file is current.
import { writeFile } from "node:fs/promises";
import { BUSINESS_TYPES, SECTORS } from "../../app-v3/catalog-data.js";

export function buildCatalogLabelsSource() {
  const types = Object.fromEntries(BUSINESS_TYPES.map(({ id, name, country }) => [
    id, country && country !== "GLOBAL" ? `${name} (${country})` : name
  ]));
  types.unlisted = "Not listed in the catalog";
  const sectors = Object.fromEntries(SECTORS.map(({ id, name }) => [id, name]));
  return "// Generated by tools/admin/build-catalog-labels.mjs from app-v3/catalog-data.js. Do not edit.\n"
    + `export const BUSINESS_TYPE_LABELS = Object.freeze(${JSON.stringify(types, null, 2)});\n`
    + `export const SECTOR_LABELS = Object.freeze(${JSON.stringify(sectors, null, 2)});\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(new URL("../../admin/catalog-labels.js", import.meta.url), buildCatalogLabelsSource());
  console.log("admin/catalog-labels.js written");
}
