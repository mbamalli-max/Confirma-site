// Ship approved business-search aliases to the app.
//
//   node tools/business-aliases/export.mjs           write app-v3/business-aliases.js
//   node tools/business-aliases/export.mjs --check   fail if the shipped file is stale or holds anything unapproved
//
// Inputs: aliases.txt (inventory; draft rows allowed) and alias-review.csv (the only record of review statuses).
// Only rows reviewed "ok" that pass the pilot rule are shipped. Asking to ship anything else is an error.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { BUSINESS_TYPES } from "../../app-v3/catalog-data.js";
import { normalizeSearchText } from "../../app-v3/business-text.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "../..");
export const DEFAULT_PATHS = {
  inventory: path.join(HERE, "aliases.txt"),
  review: path.join(HERE, "alias-review.csv"),
  out: path.join(REPO, "app-v3/business-aliases.js")
};
// Pilot: aliases may be tagged for any country or for a pilot country. Pan-African tags are future scope.
const PILOT_USED_IN = new Set(["any", "NG", "US"]);
const REVIEW_STATUSES = new Set(["draft", "ok", "fix", "drop"]);

export function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i += 1; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i += 1;
      row.push(field); field = "";
      if (row.some((value) => value !== "")) rows.push(row);
      row = [];
    } else field += ch;
  }
  row.push(field);
  if (row.some((value) => value !== "")) rows.push(row);
  const [header = [], ...body] = rows;
  return body.map((values) => Object.fromEntries(header.map((name, index) => [name.trim(), (values[index] ?? "").trim()])));
}

export function parseInventory(text) {
  const rows = [];
  text.split(/\r?\n/).forEach((raw, index) => {
    const line = raw.trim();
    if (!line || line.startsWith("#")) return;
    const [alias, typeId, kind, usedIn, note = ""] = line.split("|").map((part) => part.trim());
    rows.push({ line: index + 1, alias, type_id: typeId, kind, used_in: usedIn, note });
  });
  return rows;
}

const key = (alias, typeId) => `${normalizeSearchText(alias)}\u0000${typeId}`;

// Why a row may not ship under the pilot rule, or null when it may.
export function pilotRefusal(row, types = BUSINESS_TYPES) {
  const type = types.find((item) => item.id === row.type_id);
  if (!type) return "unknown business type";
  if (row.kind === "brand") return "brand names are pending decision D2";
  if (!PILOT_USED_IN.has(row.used_in)) return `tagged "${row.used_in}": pan-African terms are future scope`;
  if (row.used_in !== "any" && type.country !== "GLOBAL" && type.country !== row.used_in) {
    return `tagged for ${row.used_in} but the type belongs to ${type.country}`;
  }
  return null;
}

export function buildAliasExport({ inventoryText, reviewText, types = BUSINESS_TYPES }) {
  const errors = [];
  const inventory = new Map(parseInventory(inventoryText).map((row) => [key(row.alias, row.type_id), row]));
  const approved = [];
  const seen = new Set();
  for (const review of parseCsv(reviewText)) {
    const status = review.status;
    if (!REVIEW_STATUSES.has(status)) {
      errors.push(`${review.alias} -> ${review.type_id}: bad status "${status}"`);
      continue;
    }
    if (status !== "ok") continue;
    const row = inventory.get(key(review.alias, review.type_id));
    if (!row) {
      errors.push(`${review.alias} -> ${review.type_id}: approved but not in aliases.txt`);
      continue;
    }
    const refusal = pilotRefusal(row, types);
    if (refusal) {
      errors.push(`${row.alias} -> ${row.type_id}: approved but cannot ship (${refusal})`);
      continue;
    }
    const entryKey = key(row.alias, row.type_id);
    if (seen.has(entryKey)) {
      errors.push(`${row.alias} -> ${row.type_id}: approved twice`);
      continue;
    }
    seen.add(entryKey);
    approved.push({ alias: row.alias, normalised: normalizeSearchText(row.alias), type_id: row.type_id, used_in: row.used_in });
  }
  approved.sort((a, b) => a.type_id.localeCompare(b.type_id) || a.normalised.localeCompare(b.normalised));
  return { entries: approved, errors };
}

export function renderAliasModule(entries) {
  return [
    "// Generated by tools/business-aliases/export.mjs from alias-review.csv. Do not edit by hand.",
    "// Only aliases reviewed \"ok\" that pass the pilot country rule are listed here.",
    `export const BUSINESS_ALIASES = Object.freeze(${JSON.stringify(entries, null, 2)}.map((entry) => Object.freeze(entry)));`,
    ""
  ].join("\n");
}

// Independent check of a shipped list: every entry must trace to an "ok" review and the pilot rule.
export function checkShippedEntries(shipped, { inventoryText, reviewText, types = BUSINESS_TYPES }) {
  const errors = [];
  const inventory = new Map(parseInventory(inventoryText).map((row) => [key(row.alias, row.type_id), row]));
  const reviews = new Map(parseCsv(reviewText).map((row) => [key(row.alias, row.type_id), row]));
  const seen = new Set();
  for (const entry of shipped) {
    const entryKey = key(entry.alias, entry.type_id);
    const label = `${entry.alias} -> ${entry.type_id}`;
    if (seen.has(entryKey)) errors.push(`${label}: shipped twice`);
    seen.add(entryKey);
    if (entry.normalised !== normalizeSearchText(entry.alias)) errors.push(`${label}: normalised text is wrong`);
    const review = reviews.get(entryKey);
    if (!review || review.status !== "ok") errors.push(`${label}: shipped without an "ok" review (status ${review?.status || "none"})`);
    const row = inventory.get(entryKey);
    if (!row) { errors.push(`${label}: not in aliases.txt`); continue; }
    if (row.used_in !== entry.used_in) errors.push(`${label}: country tag ${entry.used_in} does not match the inventory (${row.used_in})`);
    const refusal = pilotRefusal(row, types);
    if (refusal) errors.push(`${label}: ${refusal}`);
  }
  return errors;
}

async function main() {
  const check = process.argv.includes("--check");
  const inventoryText = readFileSync(DEFAULT_PATHS.inventory, "utf8");
  const reviewText = readFileSync(DEFAULT_PATHS.review, "utf8");
  const { entries, errors } = buildAliasExport({ inventoryText, reviewText });
  if (errors.length) {
    console.error(`NOT EXPORTED\n${errors.join("\n")}`);
    process.exit(1);
  }
  const rendered = renderAliasModule(entries);
  if (!check) {
    writeFileSync(DEFAULT_PATHS.out, rendered);
    console.log(`wrote ${path.relative(REPO, DEFAULT_PATHS.out)}: ${entries.length} approved alias(es)`);
    return;
  }
  const problems = [];
  const { BUSINESS_ALIASES } = await import(`${pathToFileURL(DEFAULT_PATHS.out).href}?t=${Date.now()}`);
  problems.push(...checkShippedEntries(BUSINESS_ALIASES, { inventoryText, reviewText }));
  if (readFileSync(DEFAULT_PATHS.out, "utf8") !== rendered) problems.push("shipped file is stale: rerun the exporter");
  if (problems.length) {
    console.error(`CHECK FAILED\n${problems.join("\n")}`);
    process.exit(1);
  }
  console.log(`check ok: ${BUSINESS_ALIASES.length} approved alias(es) shipped`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  await main();
}
